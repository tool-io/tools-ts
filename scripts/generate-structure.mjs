import { mkdir, readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = path.resolve(import.meta.dirname, "..");
const packageRoot = path.join(root, "packages/tools");
const sourceRoot = path.join(packageRoot, "src");
const contractsRoot = path.join(root, "contracts");
const check = process.argv.includes("--check");

const walk = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) => left.name.localeCompare(right.name))) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(target)));
    else files.push(target);
  }
  return files;
};

const toolDirectories = [];
for (const file of await walk(sourceRoot)) {
  if (path.basename(file) !== "tool.ts") continue;
  const source = await readFile(file, "utf8");
  if (!/export\s+default\s+/.test(source)) continue;
  const directory = path.dirname(file);
  const indexFile = path.join(directory, "index.ts");
  let indexSource;
  try {
    indexSource = await readFile(indexFile, "utf8");
  } catch {
    throw new Error(`Public tool ${path.relative(sourceRoot, directory)} needs index.ts.`);
  }
  if (!/export\s*\{\s*default(?:\s*,|\s*\})[\s\S]*?from\s*["']\.\/tool\.js["']/.test(indexSource))
    throw new Error(`Public tool ${path.relative(sourceRoot, directory)} must re-export its default definition.`);
  toolDirectories.push(path.relative(sourceRoot, directory).split(path.sep).join("/"));
}
toolDirectories.sort();

const imports = toolDirectories.map(
  (directory, index) => `import tool${String(index).padStart(3, "0")} from "../${directory}/tool.js";`,
);
const entries = toolDirectories.map(
  (_, index) => `  tool${String(index).padStart(3, "0")},`,
);
const registrySource = `// Generated by scripts/generate-structure.mjs. Do not edit.
${imports.join("\n")}
import type { ToolDefinition } from "../core/definition.js";

export type RegisteredTool = ToolDefinition<unknown, unknown>;

const definitions: readonly RegisteredTool[] = [
${entries.join("\n")}
];

export const toolRegistry = new Map<string, RegisteredTool>();
for (const definition of definitions) {
  if (toolRegistry.has(definition.id))
    throw new Error(\`Duplicate generated tool ID: \${definition.id}\`);
  toolRegistry.set(definition.id, definition);
}

export const getTool = (id: string): RegisteredTool | undefined =>
  toolRegistry.get(id);
`;

const manifest = `${JSON.stringify({ schemaVersion: 1, tools: toolDirectories }, null, 2)}\n`;

const packageFile = path.join(packageRoot, "package.json");
const packageJson = JSON.parse(await readFile(packageFile, "utf8"));
const exportEntry = (directory) => ({
  types: `./dist/${directory}/index.d.ts`,
  import: `./dist/${directory}/index.js`,
});
const exports = {
  ".": { types: "./dist/index.d.ts", import: "./dist/index.js" },
  "./catalog": "./catalog.generated.json",
  "./contracts": "./contracts.generated.json",
  "./contracts/schema": "./tool-contract.schema.json",
  "./chain": exportEntry("chain"),
  "./core": exportEntry("core"),
  "./dictionary": exportEntry("dictionary"),
  "./flashcards": exportEntry("flashcards"),
  "./registry": {
    types: "./dist/registry.d.ts",
    import: "./dist/registry.js",
  },
  "./weather": exportEntry("weather"),
  "./word-relations": exportEntry("word-relations"),
};
for (const directory of toolDirectories) exports[`./${directory}`] = exportEntry(directory);
packageJson.exports = Object.fromEntries(
  Object.entries(exports).sort(([left], [right]) => left.localeCompare(right)),
);
packageJson.files = [
  "dist",
  "catalog.generated.json",
  "contracts.generated.json",
  "tool-contract.schema.json",
  "LICENSE",
  "README.md",
];
const packageSource = `${JSON.stringify(packageJson, null, 2)}\n`;

const outputs = [
  [path.join(sourceRoot, "generated/registry.generated.ts"), registrySource],
  [path.join(packageRoot, "public-tools.generated.json"), manifest],
  [packageFile, packageSource],
  [
    path.join(packageRoot, "tool-contract.schema.json"),
    await readFile(path.join(contractsRoot, "tool-contract.schema.json"), "utf8"),
  ],
];

let stale = false;
for (const [file, content] of outputs) {
  let current = "";
  try {
    current = await readFile(file, "utf8");
  } catch {}
  if (current === content) continue;
  if (check) {
    stale = true;
    process.stderr.write(`${path.relative(root, file)} is stale.\n`);
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}
if (stale) process.exitCode = 1;
