import { mkdir, readdir, readFile, rm, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = path.resolve(import.meta.dirname, "..");
const packageRoot = path.join(root, "packages/tools");
const sourceRoot = path.join(packageRoot, "src");
const contractsRoot = path.join(root, "contracts");
const check = process.argv.includes("--check");

const walk = async (directory) => {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries.sort((left, right) =>
    left.name.localeCompare(right.name),
  )) {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...(await walk(target)));
    else files.push(target);
  }
  return files;
};

const toolDirectories = [];
for (const file of await walk(sourceRoot)) {
  if (path.basename(file) !== "tool.ts") continue;
  const source = await readFile(file, "utf8");
  if (!/export\s+default\s+/.test(source)) continue;
  const directory = path.dirname(file);
  const indexFile = path.join(directory, "index.ts");
  let indexSource;
  try {
    indexSource = await readFile(indexFile, "utf8");
  } catch {
    throw new Error(
      `Public tool ${path.relative(sourceRoot, directory)} needs index.ts.`,
    );
  }
  if (
    !/export\s*\{[^}]*\bdefault\b[^}]*\}\s*from\s*["']\.\/tool\.js["']/.test(
      indexSource,
    )
  )
    throw new Error(
      `Public tool ${path.relative(sourceRoot, directory)} must re-export its default definition.`,
    );
  toolDirectories.push(
    path.relative(sourceRoot, directory).split(path.sep).join("/"),
  );
}
toolDirectories.sort();

const registryBucketCount = 256;
const registryBucketWidth = 3;
const registryBucketIndex = (id) => {
  let hash = 2166136261;
  for (let index = 0; index < id.length; index += 1) {
    hash ^= id.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0) % registryBucketCount;
};
const registryBuckets = Array.from({ length: registryBucketCount }, () => []);
for (const directory of toolDirectories)
  registryBuckets[registryBucketIndex(directory)].push(directory);

const bucketImports = registryBuckets.map(
  (_, index) =>
    `  ${index}: () => import("./registry-buckets/${String(index).padStart(registryBucketWidth, "0")}.generated.js"),`,
);
const registrySource = `// Generated by scripts/generate-structure.mjs. Do not edit.
import type { ToolDefinition } from "../core/definition.js";
import type { ToolExample } from "../core/example.js";

export type RegisteredTool = ToolDefinition<unknown, unknown>;
export type RegisteredToolModule = {
  readonly default: RegisteredTool;
  readonly example?: ToolExample<unknown, unknown>;
};
type RegistryBucket = {
  readonly toolModuleLoaders: Readonly<
    Record<string, () => Promise<RegisteredToolModule>>
  >;
};

const registryBucketCount = ${registryBucketCount};
const registryBucketLoaders: Readonly<
  Record<number, () => Promise<RegistryBucket>>
> = {
${bucketImports.join("\n")}
};
const bucketPromises = new Map<number, Promise<RegistryBucket>>();
const modulePromises = new Map<
  string,
  Promise<RegisteredToolModule | undefined>
>();

const bucketIndexFor = (id: string): number => {
  let hash = 2166136261;
  for (let index = 0; index < id.length; index += 1) {
    hash ^= id.charCodeAt(index);
    hash = Math.imul(hash, 16777619);
  }
  return (hash >>> 0) % registryBucketCount;
};

const loadBucket = (index: number): Promise<RegistryBucket> => {
  const existing = bucketPromises.get(index);
  if (existing) return existing;
  const pending = registryBucketLoaders[index]().catch((error: unknown) => {
    bucketPromises.delete(index);
    throw error;
  });
  bucketPromises.set(index, pending);
  return pending;
};

export const publicToolCount = ${toolDirectories.length};

export const loadToolModule = async (
  id: string,
): Promise<RegisteredToolModule | undefined> => {
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*(?:\\/[a-z0-9]+(?:-[a-z0-9]+)*)*$/.test(id))
    return undefined;
  const existing = modulePromises.get(id);
  if (existing) return existing;
  const pending = loadBucket(bucketIndexFor(id))
    .then(async (bucket) => {
      const load = bucket.toolModuleLoaders[id];
      if (!load) return undefined;
      const module = await load();
      if (module.default.id !== id)
        throw new Error(\`Loaded tool \${id} does not export its matching definition.\`);
      return module;
    })
    .catch((error: unknown) => {
      modulePromises.delete(id);
      throw error;
    });
  modulePromises.set(id, pending);
  const module = await pending;
  if (!module) modulePromises.delete(id);
  return module;
};

export const loadTool = async (
  id: string,
): Promise<RegisteredTool | undefined> =>
  (await loadToolModule(id))?.default;

/** @deprecated Use loadTool to make asynchronous loading explicit. */
export const getTool = loadTool;
`;

const registryBucketSources = registryBuckets.map((directories) => {
  const loaders = directories.map(
    (directory) =>
      `  ${JSON.stringify(directory)}: () => import("../../${directory}/index.js"),`,
  );
  return `// Generated by scripts/generate-structure.mjs. Do not edit.
import type { RegisteredToolModule } from "../registry.generated.js";

export const toolModuleLoaders: Readonly<
  Record<string, () => Promise<RegisteredToolModule>>
> = {
${loaders.join("\n")}
};
`;
});

const manifest = `${JSON.stringify({ schemaVersion: 1, tools: toolDirectories }, null, 2)}\n`;

const packageFile = path.join(packageRoot, "package.json");
const packageJson = JSON.parse(await readFile(packageFile, "utf8"));
const exportEntry = (directory) => ({
  types: `./dist/${directory}/index.d.ts`,
  import: `./dist/${directory}/index.js`,
});
const rootExportEntry = (name) => ({
  types: `./dist/${name}.d.ts`,
  import: `./dist/${name}.js`,
});
const exports = {
  ".": { types: "./dist/index.d.ts", import: "./dist/index.js" },
  "./catalog": "./catalog.generated.json",
  "./contracts": "./contracts.generated.json",
  "./contracts/schema": "./tool-contract.schema.json",
  "./chain": exportEntry("chain"),
  "./core": exportEntry("core"),
  "./dictionary": exportEntry("dictionary"),
  "./discovery": rootExportEntry("discovery"),
  "./flashcards": exportEntry("flashcards"),
  "./registry": {
    types: "./dist/registry.d.ts",
    import: "./dist/registry.js",
  },
  "./runtime": rootExportEntry("runtime"),
  "./weather": exportEntry("weather"),
  "./word-relations": exportEntry("word-relations"),
};
exports["./*"] = exportEntry("*");
packageJson.exports = Object.fromEntries(
  Object.entries(exports).sort(([left], [right]) => left.localeCompare(right)),
);
packageJson.files = [
  "dist",
  "catalog.generated.json",
  "contracts.generated.json",
  "tool-contract.schema.json",
  "LICENSE",
  "README.md",
];
const packageSource = `${JSON.stringify(packageJson, null, 2)}\n`;

const outputs = [
  [path.join(sourceRoot, "generated/registry.generated.ts"), registrySource],
  ...registryBucketSources.map((source, index) => [
    path.join(
      sourceRoot,
      `generated/registry-buckets/${String(index).padStart(registryBucketWidth, "0")}.generated.ts`,
    ),
    source,
  ]),
  [path.join(packageRoot, "public-tools.generated.json"), manifest],
  [packageFile, packageSource],
  [
    path.join(packageRoot, "tool-contract.schema.json"),
    await readFile(
      path.join(contractsRoot, "tool-contract.schema.json"),
      "utf8",
    ),
  ],
];

const expectedOutputFiles = new Set(outputs.map(([file]) => file));
const registryBucketRoot = path.join(sourceRoot, "generated/registry-buckets");
let stale = false;
for (const entry of await readdir(registryBucketRoot, {
  withFileTypes: true,
}).catch(() => [])) {
  if (
    !entry.isFile() ||
    !/^\d+\.generated\.ts$/.test(entry.name) ||
    expectedOutputFiles.has(path.join(registryBucketRoot, entry.name))
  )
    continue;
  if (check) {
    stale = true;
    process.stderr.write(
      `${path.relative(root, path.join(registryBucketRoot, entry.name))} is stale.\n`,
    );
  } else {
    await rm(path.join(registryBucketRoot, entry.name));
  }
}

for (const [file, content] of outputs) {
  let current = "";
  try {
    current = await readFile(file, "utf8");
  } catch {}
  if (current === content) continue;
  if (check) {
    stale = true;
    process.stderr.write(`${path.relative(root, file)} is stale.\n`);
  } else {
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, content);
  }
}
if (stale) process.exitCode = 1;
