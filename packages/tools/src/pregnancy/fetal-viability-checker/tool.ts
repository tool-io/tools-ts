import type { ToolExample } from "../../core/example.js";
import { createSimpleTool, type SimpleField } from "../../core/simple.js";
import {
  validateInput,
  finish,
  annotatedChecklist,
} from "../batch47-shared.js";
export type Input = Readonly<{
  readonly independentlyWitnessedCriterionFlags: readonly number[];
  readonly criterionKnownFlags: readonly number[];
}>;
export type Output = { readonly result: Readonly<Record<string, unknown>> };
const fields = [
  {
    id: "independentlyWitnessedCriterionFlags",
    label: "Independently witnessed criterion flags",
    kind: "numberList",
  },
  {
    id: "criterionKnownFlags",
    label: "Criterion known flags",
    kind: "numberList",
  },
] as const satisfies readonly SimpleField[];
const compute = (input: Input): Readonly<Record<string, unknown>> => {
  return annotatedChecklist(
    [
      "qualified clinical assessment recorded",
      "actual gestational dating evidence reviewed",
      "actual fetal assessment evidence reviewed",
      "context and uncertainty reviewed",
    ],
    input.independentlyWitnessedCriterionFlags,
    input.criterionKnownFlags,
  );
};
export const calculate = (input: Input): Output => {
  validateInput(input, fields);
  return finish({ result: compute(input) });
};
export const example = {
  input: {
    independentlyWitnessedCriterionFlags: [1, 1, 1, 1],
    criterionKnownFlags: [1, 1, 1, 1],
  },
  output: {
    result: {
      witnessedCriteria: [
        "qualified clinical assessment recorded",
        "actual gestational dating evidence reviewed",
        "actual fetal assessment evidence reviewed",
        "context and uncertainty reviewed",
      ],
      knownMissingCriteria: [],
      unknownCriteria: [],
    },
  },
} satisfies ToolExample<Input, Output>;
export const tool = createSimpleTool({
  id: "pregnancy/fetal-viability-checker",
  title: "Fetal Viability Checker",
  description:
    "Viability evidence review only. Gestational age alone does not determine current/future viability; no binary survival prediction or reassurance. Independently established criterion columns: qualified clinical assessment recorded, actual gestational dating evidence reviewed, actual fetal assessment evidence reviewed, context and uncertainty reviewed. Unknown/missing evidence retained. Not readiness, eligibility, diagnosis, treatment, safety or compliance approval.",
  inputs: fields,
  outputs: [
    {
      id: "result",
      label: "Qualified observation, conditional calculation or reference",
      kind: "object",
    },
  ],
  calculate: (value) => calculate(value as unknown as Input),
});
export const run = tool.execute;
export default tool;
