import type { ToolExample } from "../../core/example.js";
import { createSimpleTool, simpleError } from "../../core/simple.js";

export type AdRevenueInput = {
  readonly impressionsPerUser: number;
  readonly monthlyUsersPerTool: number;
  readonly revenuePerThousandImpressions: number;
  readonly targetRevenue: number;
};

export type AdRevenueOutput = {
  readonly impressionsNeeded: number;
  readonly revenuePerUser: number;
  readonly toolsNeeded: number;
  readonly usersNeeded: number;
};

export const calculateAdRevenue = (input: AdRevenueInput): AdRevenueOutput => {
  if (!(input.revenuePerThousandImpressions > 0))
    simpleError(
      "revenuePerThousandImpressions",
      "Revenue per thousand impressions must be greater than zero.",
      "rate_not_positive",
    );
  if (!(input.impressionsPerUser > 0))
    simpleError(
      "impressionsPerUser",
      "Impressions per user must be greater than zero.",
      "impressions_not_positive",
    );
  if (!(input.monthlyUsersPerTool > 0))
    simpleError(
      "monthlyUsersPerTool",
      "Monthly users per tool must be greater than zero.",
      "users_per_tool_not_positive",
    );
  const impressionsNeeded =
    (input.targetRevenue * 1_000) / input.revenuePerThousandImpressions;
  const usersNeeded = impressionsNeeded / input.impressionsPerUser;
  const revenuePerUser =
    (input.impressionsPerUser * input.revenuePerThousandImpressions) / 1_000;
  const toolsNeeded = usersNeeded / input.monthlyUsersPerTool;
  if (
    ![impressionsNeeded, usersNeeded, revenuePerUser, toolsNeeded].every(
      Number.isFinite,
    )
  )
    simpleError(
      "targetRevenue",
      "The requested scenario is outside the supported numeric range.",
      "result_not_finite",
    );
  return { impressionsNeeded, revenuePerUser, toolsNeeded, usersNeeded };
};

export const adRevenueExample = {
  input: {
    impressionsPerUser: 10,
    monthlyUsersPerTool: 5_000,
    revenuePerThousandImpressions: 5,
    targetRevenue: 10_000,
  },
  output: {
    impressionsNeeded: 2_000_000,
    revenuePerUser: 0.05,
    toolsNeeded: 40,
    usersNeeded: 200_000,
  },
} satisfies ToolExample<AdRevenueInput, AdRevenueOutput>;

export const adRevenueTool = createSimpleTool({
  calculate: (input) =>
    calculateAdRevenue({
      impressionsPerUser: input.impressionsPerUser as number,
      monthlyUsersPerTool: input.monthlyUsersPerTool as number,
      revenuePerThousandImpressions:
        input.revenuePerThousandImpressions as number,
      targetRevenue: input.targetRevenue as number,
    }),
  description:
    "Estimate impressions, users, and equally trafficked tools needed to reach an advertising-revenue target from an RPM assumption.",
  id: "finance/ad-revenue",
  inputs: [
    {
      description: "Revenue earned per 1,000 ad impressions.",
      id: "revenuePerThousandImpressions",
      kind: "number",
      label: "Revenue per thousand impressions",
      minimum: 0,
    },
    {
      description: "Average monetized impressions generated by one user.",
      id: "impressionsPerUser",
      kind: "number",
      label: "Impressions per user",
      minimum: 0,
    },
    {
      description: "Average monthly users expected for each tool.",
      id: "monthlyUsersPerTool",
      kind: "number",
      label: "Monthly users per tool",
      minimum: 0,
    },
    {
      description: "Revenue target in the same currency as the RPM input.",
      id: "targetRevenue",
      kind: "number",
      label: "Target revenue",
      minimum: 0,
    },
  ],
  outputs: [
    {
      id: "impressionsNeeded",
      kind: "number",
      label: "Impressions needed",
    },
    { id: "usersNeeded", kind: "number", label: "Users needed" },
    { id: "toolsNeeded", kind: "number", label: "Tools needed" },
    {
      id: "revenuePerUser",
      kind: "number",
      label: "Revenue per user",
    },
  ],
  title: "Advertising Revenue Target Calculator",
});

export const runAdRevenue = adRevenueTool.execute;
export default adRevenueTool;
