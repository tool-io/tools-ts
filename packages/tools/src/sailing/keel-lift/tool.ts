import type { ToolExample } from "../../core/example.js";
import { createSimpleTool, simpleError } from "../../core/simple.js";

export type KeelLiftInput = {
  readonly boatSpeedMs: number;
  readonly keelAreaM2: number;
  readonly liftCoefficient?: number;
};

export type KeelLiftOutput = {
  readonly keelLiftNewtons: number;
};

const SEAWATER_DENSITY_KG_PER_M3 = 1025;
const DEFAULT_LIFT_COEFFICIENT = 1;

export const keelLiftExample = {
  input: { boatSpeedMs: 4, keelAreaM2: 2 },
  output: { keelLiftNewtons: 16400 },
} satisfies ToolExample<KeelLiftInput, KeelLiftOutput>;

const keelLiftNewtons = (
  boatSpeedMs: number,
  keelAreaM2: number,
  liftCoefficient: number,
): number =>
  0.5 *
  SEAWATER_DENSITY_KG_PER_M3 *
  boatSpeedMs *
  boatSpeedMs *
  keelAreaM2 *
  liftCoefficient;

export const keelLiftTool = createSimpleTool({
  id: "sailing/keel-lift",
  title: "Keel Lift Calculator",
  description:
    "Compute the hydrodynamic lift generated by a keel from boat speed, keel area, and a lift coefficient.",
  inputs: [
    {
      description: "Boat speed through the water.",
      id: "boatSpeedMs",
      kind: "number",
      label: "Boat speed",
      minimum: 0,
      unit: "m/s",
    },
    {
      description: "Projected keel area.",
      id: "keelAreaM2",
      kind: "number",
      label: "Keel area",
      minimum: 0,
      unit: "m\u00B2",
    },
    {
      default: DEFAULT_LIFT_COEFFICIENT,
      description: "Section lift coefficient between zero and two.",
      id: "liftCoefficient",
      kind: "number",
      label: "Lift coefficient",
      maximum: 2,
      minimum: 0,
    },
  ],
  outputs: [
    {
      description: "Hydrodynamic lift force on the keel.",
      format: "force",
      id: "keelLiftNewtons",
      kind: "number",
      label: "Keel lift",
      unit: "N",
    },
  ],
  calculate: (input) => {
    const boatSpeedMs = input.boatSpeedMs as number;
    const keelAreaM2 = input.keelAreaM2 as number;
    if (boatSpeedMs < 0)
      simpleError(
        "boatSpeedMs",
        "Boat speed cannot be negative.",
        "invalid_speed",
      );
    if (keelAreaM2 < 0)
      simpleError(
        "keelAreaM2",
        "Keel area cannot be negative.",
        "invalid_area",
      );
    return {
      keelLiftNewtons: keelLiftNewtons(
        boatSpeedMs,
        keelAreaM2,
        input.liftCoefficient as number,
      ),
    };
  },
});
export const runKeelLift = keelLiftTool.execute;
export default keelLiftTool;
