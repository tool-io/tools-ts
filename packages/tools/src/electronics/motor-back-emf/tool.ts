import type { ToolExample } from "../../core/example.js";
import { createSimpleTool, simpleError } from "../../core/simple.js";

export type MotorBackEmfInput = {
  readonly kvRpmPerVoltNumber?: number;
  readonly rpmInt: number;
};

export type MotorBackEmfOutput = {
  readonly backEmfVolts: number;
};

export const motorBackEmfExample = {
  input: { kvRpmPerVoltNumber: 1000, rpmInt: 10000 },
  output: { backEmfVolts: 10 },
} satisfies ToolExample<MotorBackEmfInput, MotorBackEmfOutput>;

export const calculateMotorBackEmf = (
  input: MotorBackEmfInput,
): MotorBackEmfOutput => {
  const kvRpmPerVolt = input.kvRpmPerVoltNumber ?? 100;
  if (!(kvRpmPerVolt > 0))
    simpleError("kvRpmPerVoltNumber", "Kv must be positive.", "invalid_kv");
  if (!Number.isSafeInteger(input.rpmInt) || input.rpmInt < 0)
    simpleError(
      "rpmInt",
      "Speed must be a non-negative integer.",
      "invalid_rpm",
    );
  return { backEmfVolts: input.rpmInt / kvRpmPerVolt };
};

export const motorBackEmfTool = createSimpleTool({
  calculate: (input) =>
    calculateMotorBackEmf(input as unknown as MotorBackEmfInput),
  description:
    "Compute the back EMF of a brushless motor in volts as shaft speed divided by its Kv constant in rpm per volt.",
  id: "electronics/motor-back-emf",
  inputs: [
    {
      description: "Shaft speed in revolutions per minute.",
      id: "rpmInt",
      kind: "integer",
      label: "Speed",
      unit: "rpm",
    },
    {
      default: 100,
      description: "Motor velocity constant in rpm per volt.",
      id: "kvRpmPerVoltNumber",
      kind: "number",
      label: "Kv",
      unit: "rpm/V",
    },
  ],
  outputs: [
    {
      description: "Back EMF generated by the spinning motor.",
      id: "backEmfVolts",
      kind: "number",
      label: "Back EMF",
      unit: "V",
    },
  ],
  title: "Motor Back EMF",
});
export const runMotorBackEmf = motorBackEmfTool.execute;
export default motorBackEmfTool;
