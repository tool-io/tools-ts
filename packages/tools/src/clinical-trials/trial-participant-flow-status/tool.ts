import * as H from "../../core/batch60-schema-calculation.js";
import type { ToolExample } from "../../core/example.js";

export type Input = {
  readonly participantId: string;
  readonly flowStatusCode: string;
  readonly source: string;
};
export type Output = { readonly token: string };
export const inputSchema = {
  type: "object",
  additionalProperties: false,
  properties: {
    participantId: { type: "string", maxLength: 8192, minLength: 1 },
    flowStatusCode: { type: "string", maxLength: 8192, minLength: 1 },
    source: { type: "string", maxLength: 8192, minLength: 1 },
  },
  required: ["participantId", "flowStatusCode", "source"],
} as const;
export const outputSchema = {
  type: "object",
  additionalProperties: false,
  properties: { token: { type: "string", maxLength: 8192 } },
  required: ["token"],
} as const;
/** Preserve an explicit participant-flow code by source without inferring disposition. */
export function calculate(request: Input): Output {
  H.requireInput(request, inputSchema);
  const { participantId, flowStatusCode, source } = request;
  const compute = (): Output => {
    H.domain(participantId.length > 0, "participantId");
    H.domain(flowStatusCode.length > 0, "flowStatusCode");
    H.domain(source.length > 0, "source");
    return { token: JSON.stringify([participantId, flowStatusCode, source]) };
  };
  const calculated = H.canonicalOutput(compute());
  H.requireOutput(calculated, outputSchema);
  return calculated;
}
export const example = {
  input: {
    participantId: "P17",
    flowStatusCode: "screened",
    source: "Flow dictionary",
  },
  output: { token: '["P17","screened","Flow dictionary"]' },
} satisfies ToolExample<Input, Output>;
