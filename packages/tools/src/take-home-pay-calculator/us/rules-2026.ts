export type TaxRateRow = readonly [
  lower: number,
  upper: number,
  base: number,
  rate: number,
];

export const taxFromRows = (
  income: number,
  rows: readonly TaxRateRow[],
): number => {
  const row = rows.find(([, upper]) => income < upper) ?? rows[rows.length - 1];
  if (!row) return 0;
  return row[2] + Math.max(0, income - row[0]) * row[3];
};

