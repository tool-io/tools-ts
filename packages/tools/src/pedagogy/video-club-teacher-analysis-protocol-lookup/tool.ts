import type { ToolExample } from "../../core/example.js";
import { createSimpleTool, type SimpleField } from "../../core/simple.js";
import { validateInput, finish, stageAudit } from "../batch41-shared.js";
export type Input = Readonly<{
  readonly callerObservedVideoClubStageIds: readonly string[];
  readonly callerStageDeclaredOrder: readonly string[];
}>;
export type Output = Readonly<{
  readonly missingDeclaredStageIds: readonly string[];
  readonly orderInversionIndices: readonly number[];
}>;
const inputFields = [
  {
    id: "callerObservedVideoClubStageIds",
    label: "Caller observed video club stage ids",
    kind: "stringList",
  },
  {
    id: "callerStageDeclaredOrder",
    label: "Caller stage declared order",
    kind: "stringList",
  },
] as const satisfies readonly SimpleField[];
const compute = (input: Input): Output => {
  return stageAudit(
    input.callerObservedVideoClubStageIds,
    input.callerStageDeclaredOrder,
  );
};
export const calculate = (input: Input): Output => {
  validateInput(input, inputFields);
  return finish(compute(input));
};
export const exampleInput = {
  callerObservedVideoClubStageIds: ["select-clip", "plan-next-observation"],
  callerStageDeclaredOrder: [
    "select-clip",
    "describe-evidence",
    "interpret-with-context",
    "consider-alternatives",
    "plan-next-observation",
  ],
} satisfies Input;
export const exampleOutput = {
  missingDeclaredStageIds: [
    "describe-evidence",
    "interpret-with-context",
    "consider-alternatives",
  ],
  orderInversionIndices: [],
} satisfies Output;
export const example = {
  input: exampleInput,
  output: exampleOutput,
} satisfies ToolExample<Input, Output>;
export const tool = createSimpleTool({
  id: "pedagogy/video-club-teacher-analysis-protocol-lookup",
  title: "Video Club Teacher Analysis Protocol Lookup",
  description:
    "Caller declared non-evaluative video club observation/analysis process coverage, not teacher performance evaluation. Audit exact supplied observed stages against the independently verified declared order, not pedagogical/performance efficacy. Caller independently verifies learner/context/evidence and reference edition; not causal learning efficacy, disability eligibility or educational certification.",
  inputs: inputFields,
  outputs: [
    {
      id: "missingDeclaredStageIds",
      label: "Missing declared stage ids",
      kind: "stringList",
    },
    {
      id: "orderInversionIndices",
      label: "Order inversion indices",
      kind: "numberList",
    },
  ],
  calculate: (value) =>
    calculate({
      callerObservedVideoClubStageIds:
        value.callerObservedVideoClubStageIds as readonly string[],
      callerStageDeclaredOrder:
        value.callerStageDeclaredOrder as readonly string[],
    }),
});
export const run = tool.execute;
export default tool;
