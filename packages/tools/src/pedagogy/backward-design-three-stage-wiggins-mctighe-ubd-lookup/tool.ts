import type { ToolExample } from "../../core/example.js";
import { createSimpleTool, type SimpleField } from "../../core/simple.js";
import { validateInput, finish, stageAudit } from "../batch41-shared.js";
export type Input = Readonly<{
  readonly callerObservedBackwardDesignStageIds: readonly string[];
  readonly callerStageDeclaredOrder: readonly string[];
}>;
export type Output = Readonly<{
  readonly missingDeclaredStageIds: readonly string[];
  readonly orderInversionIndices: readonly number[];
}>;
const inputFields = [
  {
    id: "callerObservedBackwardDesignStageIds",
    label: "Caller observed backward design stage ids",
    kind: "stringList",
  },
  {
    id: "callerStageDeclaredOrder",
    label: "Caller stage declared order",
    kind: "stringList",
  },
] as const satisfies readonly SimpleField[];
const compute = (input: Input): Output => {
  return stageAudit(
    input.callerObservedBackwardDesignStageIds,
    input.callerStageDeclaredOrder,
  );
};
export const calculate = (input: Input): Output => {
  validateInput(input, inputFields);
  return finish(compute(input));
};
export const exampleInput = {
  callerObservedBackwardDesignStageIds: ["desired-results", "learning-plan"],
  callerStageDeclaredOrder: [
    "desired-results",
    "acceptable-evidence",
    "learning-plan",
  ],
} satisfies Input;
export const exampleOutput = {
  missingDeclaredStageIds: ["acceptable-evidence"],
  orderInversionIndices: [],
} satisfies Output;
export const example = {
  input: exampleInput,
  output: exampleOutput,
} satisfies ToolExample<Input, Output>;
export const tool = createSimpleTool({
  id: "pedagogy/backward-design-three-stage-wiggins-mctighe-ubd-lookup",
  title: "Backward Design Three Stage Wiggins Mctighe UbD Lookup",
  description:
    "Audit the three Understanding by Design stages: desired results, acceptable evidence and learning plan. Reports missing stages and order inversions; distinct from standards-alignment coverage and not proof of instructional efficacy.",
  inputs: inputFields,
  outputs: [
    {
      id: "missingDeclaredStageIds",
      label: "Missing declared stage ids",
      kind: "stringList",
    },
    {
      id: "orderInversionIndices",
      label: "Order inversion indices",
      kind: "numberList",
    },
  ],
  calculate: (value) =>
    calculate({
      callerObservedBackwardDesignStageIds:
        value.callerObservedBackwardDesignStageIds as readonly string[],
      callerStageDeclaredOrder:
        value.callerStageDeclaredOrder as readonly string[],
    }),
});
export const run = tool.execute;
export default tool;
