import * as H from "../../core/batch60-schema-calculation.js";
import type { ToolExample } from "../../core/example.js";

export type Input = {
  readonly productId: string;
  readonly recipeId: string;
  readonly version: string;
};
export type Output = { readonly token: string };
export const inputSchema = {
  type: "object",
  additionalProperties: false,
  properties: {
    productId: { type: "string", maxLength: 8192, minLength: 1 },
    recipeId: { type: "string", maxLength: 8192, minLength: 1 },
    version: { type: "string", maxLength: 8192, minLength: 1 },
  },
  required: ["productId", "recipeId", "version"],
} as const;
export const outputSchema = {
  type: "object",
  additionalProperties: false,
  properties: { token: { type: "string", maxLength: 8192 } },
  required: ["token"],
} as const;
/** Qualify an explicit manufacturing recipe identifier by version without providing a recipe. */
export function calculate(request: Input): Output {
  H.requireInput(request, inputSchema);
  const { productId, recipeId, version } = request;
  const compute = (): Output => {
    H.domain(productId.length > 0, "productId");
    H.domain(recipeId.length > 0, "recipeId");
    H.domain(version.length > 0, "version");
    return { token: JSON.stringify([productId, recipeId, version]) };
  };
  const calculated = H.canonicalOutput(compute());
  H.requireOutput(calculated, outputSchema);
  return calculated;
}
export const example = {
  input: { productId: "PR17", recipeId: "REC2", version: "v2" },
  output: { token: '["PR17","REC2","v2"]' },
} satisfies ToolExample<Input, Output>;
